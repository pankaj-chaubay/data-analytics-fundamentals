"""python -m fda  ->  writes data/ and reports/results.md"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from . import fraud, quality, sales  # noqa: E402

BLUE, GREY, INK, INK2, SURFACE = "#2a78d6", "#b9b8b2", "#0b0b0b", "#52514e", "#fcfcfb"


def md(df: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(lines)


def style(ax):
    ax.set_facecolor(SURFACE)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=INK2, labelsize=9)


def main(argv=None) -> None:
    p = argparse.ArgumentParser(prog="fda")
    p.add_argument("--data", default="data")
    p.add_argument("--out", default="reports")
    a = p.parse_args(argv)
    data, out = Path(a.data), Path(a.out)
    (out / "figures").mkdir(parents=True, exist_ok=True)
    data.mkdir(parents=True, exist_ok=True)

    # ---- Task 1 ------------------------------------------------------------
    s = sales.generate()
    s.to_csv(data / "retail_sales.csv", index=False)
    X, names = sales.design(s)
    y = s["sales_k"].to_numpy()
    sol = sales.solve(X, y)
    coef = pd.DataFrame({"term": names, **{k: np.round(v, 3) for k, v in sol.items() if k != "condition_number"}})
    agree = max(np.abs(sol["normal_equations"] - sol["lstsq"]).max(), np.abs(sol["qr"] - sol["lstsq"]).max())
    svd = sales.seasonal_svd(s)
    bt = sales.backtest(s)
    fc = sales.forecast(s, sol["lstsq"])
    fc_up = sales.forecast(s, sol["lstsq"], marketing_change=0.2)
    fc.to_csv(out / "sales_forecast.csv", index=False)

    fig, ax = plt.subplots(figsize=(7, 3.2), facecolor=SURFACE)
    tot = s.groupby("month")["sales_k"].sum()
    ftot = fc.groupby("month")["forecast_sales_k"].sum()
    ax.plot([pd.Period(m, "M").to_timestamp() for m in tot.index], tot.values, color=INK2, lw=2, label="Actual")
    ax.plot([pd.Period(m, "M").to_timestamp() for m in ftot.index], ftot.values, color=BLUE, lw=2, label="Forecast")
    ax.set_ylabel("Sales, thousand EUR", color=INK2, fontsize=9)
    ax.set_title("Monthly sales, all regions", loc="left", fontsize=11, color=INK)
    ax.legend(frameon=False, fontsize=8)
    style(ax)
    fig.tight_layout()
    fig.savefig(out / "figures" / "sales.png", dpi=150, facecolor=SURFACE)
    plt.close(fig)

    # ---- Task 2 ------------------------------------------------------------
    q = quality.bands(quality.generate())
    q.drop(columns=["temperature_band", "humidity_band"]).to_csv(data / "production_quality.csv", index=False)
    anova = quality.anova_table(q)
    tt = quality.shift_ttest(q)
    tukey = quality.tukey_temperature(q)
    best = quality.best_temperature(q)
    ols = quality.ols_table(q)
    band_means = q.groupby("temperature_band", observed=True)["quality_score"].agg(["mean", "size"]).round(2).reset_index()

    # ---- Task 3 ------------------------------------------------------------
    f = fraud.generate()
    f.drop(columns=["is_fraud"]).to_csv(data / "card_transactions.csv", index=False)
    f[["transaction_id", "is_fraud"]].to_csv(data / "card_transactions_labels.csv", index=False)
    sc = fraud.scores(f)
    ev = fraud.evaluate(f, sc)

    summary = {
        "sales": {"r_squared": round(sales.r_squared(X, y, sol["lstsq"]), 3), "condition_number": round(sol["condition_number"], 1),
                  "max_difference_between_solvers": float(agree), "svd_explained_share": svd["explained_share"], **bt,
                  "next_6_months_total_k": round(float(fc["forecast_sales_k"].sum()), 1),
                  "next_6_months_total_with_20pct_more_marketing_k": round(float(fc_up["forecast_sales_k"].sum()), 1)},
        "quality": {**tt, **best},
        "fraud": {"transactions": int(len(f)), "fraud_share": round(float(f["is_fraud"].mean()), 4)},
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")

    rep = [
        "# Results",
        "",
        "All data is generated by this repository (see `data/`). Numbers change only if the seeds change.",
        "",
        "## Task 1: retail sales",
        "",
        f"Regression on {len(s)} region-months. R² = {summary['sales']['r_squared']}. Condition number of X = {summary['sales']['condition_number']}.",
        f"Normal equations, QR and least squares agree to {agree:.1e}.",
        "",
        md(coef),
        "",
        f"SVD of the region x month matrix: the first component explains {svd['explained_share'][0]:.0%} of the variation, so one seasonal curve is shared by all regions.",
        f"Backtest on the last {bt['holdout_months']} months: MAPE {bt['mape_pct']}%.",
        f"Next six months: {summary['sales']['next_6_months_total_k']:,} thousand EUR; with 20% more marketing: {summary['sales']['next_6_months_total_with_20pct_more_marketing_k']:,}.",
        "",
        "![sales](figures/sales.png)",
        "",
        "## Task 2: production quality",
        "",
        md(anova),
        "",
        md(band_means),
        "",
        f"Day vs night shift (Welch t-test): {tt['day_mean']} vs {tt['night_mean']}, t = {tt['t']}, p = {tt['p_value']}, Cohen's d = {tt['cohens_d']}.",
        f"Regression with a temperature curve puts the best temperature at {best['best_temperature_c']} °C.",
        "",
        "All factors in one regression:",
        "",
        md(ols),
        "",
        "Tukey HSD, temperature bands:",
        "",
        md(tukey),
        "",
        "## Task 3: card fraud",
        "",
        f"{len(f):,} transactions, {f['is_fraud'].mean():.1%} fraud. Each method flags the top 2% for manual review.",
        "",
        md(ev),
        "",
    ]
    (out / "results.md").write_text("\n".join(rep), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(anova.to_string(index=False))
    print(ev.to_string(index=False))


if __name__ == "__main__":
    main()
